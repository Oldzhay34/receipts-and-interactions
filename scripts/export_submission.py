"""Assemble the Phase 1 submission package in ``submission/``.

Contents:

* ``Phase1_Report.docx`` and its ``Phase1_Report_sources.csv`` (``reports/build_report.py``);
* ``notebooks/``: the stage notebooks. Pass ``--executed-notebooks DIR`` with the notebooks
  downloaded from Colab after the full-data run (File > Download > .ipynb) so that they carry
  their outputs; without it the repository copies (no outputs) are used and a warning is printed;
* ``src.zip``: ``src/``, ``config/``, ``pyproject.toml`` and ``requirements.txt``;
* ``phase1_pipeline.py``: one script that runs every stage in order. It is GENERATED from the
  notebooks (their code cells, without the Colab set-up cell), so the notebooks stay the single
  source of the stage logic;
* ``MANIFEST.txt``: every file with its size and SHA-256, and whether each notebook has outputs.

Usage::

    python scripts/export_submission.py [--executed-notebooks DIR] [--out submission]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import textwrap
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
REPORT = REPO_ROOT / "reports" / "Phase1_Report.docx"
SOURCES = REPO_ROOT / "reports" / "Phase1_Report_sources.csv"
NOTEBOOKS = REPO_ROOT / "notebooks"
SRC_PARTS = ("src", "config", "pyproject.toml", "requirements.txt")

PIPELINE_HEADER = '''"""Phase 1 pipeline: runs the code of every stage notebook in order.

Generated by scripts/export_submission.py from notebooks/{first} ... {last}; edit the notebooks,
not this file. Each stage reads its inputs from and writes a new version to DATA_ROOT/outputs.

    pip install -r requirements.txt && pip install -e .
    python phase1_pipeline.py --data-root /path/to/data            # all stages
    python phase1_pipeline.py --data-root /path/to/data --from 03  # stage 03 onwards
"""

from __future__ import annotations

import argparse
import os

import matplotlib

matplotlib.use("Agg")


def display(*objects, **kwargs):  # notebook display() -> plain print
    for obj in objects:
        print(obj)

'''

PIPELINE_MAIN = """

STAGES = {stages}


def main() -> None:
    ap = argparse.ArgumentParser(description="Run the Phase 1 stages in order.")
    ap.add_argument("--data-root", default=os.environ.get("DATA_ROOT"))
    ap.add_argument("--from", dest="start", default=None, help="first stage number, e.g. 03")
    ap.add_argument("--only", nargs="*", default=None, help="stage numbers to run")
    args = ap.parse_args()
    if not args.data_root:
        ap.error("set --data-root or the DATA_ROOT environment variable")
    os.environ["DATA_ROOT"] = args.data_root
    from recsys.config import load_config

    cfg = load_config()
    for number, func in STAGES:
        if args.only is not None and number not in args.only:
            continue
        if args.start is not None and number < args.start:
            continue
        print(f"\\n===== stage {{number}}: {{func.__name__}} =====")
        func(cfg)


if __name__ == "__main__":
    main()
"""


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def stage_notebooks() -> list[Path]:
    return sorted(p for p in NOTEBOOKS.glob("[0-9][0-9]_*.ipynb"))


def code_cells(nb_path: Path) -> list[str]:
    nb = json.loads(nb_path.read_text(encoding="utf-8"))
    return ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]


def has_outputs(nb_path: Path) -> bool:
    nb = json.loads(nb_path.read_text(encoding="utf-8"))
    return any(c.get("outputs") for c in nb["cells"] if c["cell_type"] == "code")


def generate_pipeline(notebooks: list[Path]) -> str:
    """One function per notebook (code cells after the Colab cell; shell / magic lines dropped)."""
    parts = [PIPELINE_HEADER.format(first=notebooks[0].name, last=notebooks[-1].name)]
    stages = []
    for nb in notebooks:
        number, name = nb.stem.split("_", 1)
        func = f"stage_{number}_{name}"
        body_lines = []
        for src in code_cells(nb)[1:]:
            lines = [ln for ln in src.splitlines() if not ln.lstrip().startswith(("!", "%"))]
            body_lines.extend([*lines, ""])
        body = textwrap.indent("\n".join(body_lines).strip() + "\n", "    ")
        parts.append(
            f"\ndef {func}(CFG):\n"
            f'    """{nb.name} (generated)."""\n'
            f"    import matplotlib.pyplot as plt\n\n"
            f"{body}"
            f"    plt.close('all')\n\n"
        )
        stages.append(f'("{number}", {func})')
    parts.append(PIPELINE_MAIN.format(stages="[\n    " + ",\n    ".join(stages) + ",\n]"))
    source = "".join(parts)
    compile(source, "phase1_pipeline.py", "exec")  # fail early on a broken notebook
    return source


def zip_src(dest: Path) -> None:
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as zf:
        for part in SRC_PARTS:
            p = REPO_ROOT / part
            files = [p] if p.is_file() else sorted(p.rglob("*"))
            for f in files:
                if f.is_file() and "__pycache__" not in f.parts and f.suffix != ".pyc":
                    zf.write(f, f.relative_to(REPO_ROOT).as_posix())


def export(out: Path, executed: Path | None) -> list[str]:
    warnings: list[str] = []
    if out.exists():
        shutil.rmtree(out)
    (out / "notebooks").mkdir(parents=True)

    for f in (REPORT, SOURCES):
        if f.is_file():
            shutil.copy2(f, out / f.name)
        else:
            warnings.append(
                f"{f.relative_to(REPO_ROOT)} missing: run reports/build_report.py first"
            )

    repo_nbs = stage_notebooks()
    for nb in repo_nbs:
        src = executed / nb.name if executed and (executed / nb.name).is_file() else nb
        shutil.copy2(src, out / "notebooks" / nb.name)
        if not has_outputs(out / "notebooks" / nb.name):
            warnings.append(f"notebooks/{nb.name} has no outputs (pass the Colab-executed copy)")

    zip_src(out / "src.zip")
    (out / "phase1_pipeline.py").write_text(generate_pipeline(repo_nbs), encoding="utf-8")

    lines = ["file\tbytes\tsha256\tnote"]
    for f in sorted(p for p in out.rglob("*") if p.is_file()):
        rel = f.relative_to(out).as_posix()
        note = ""
        if f.suffix == ".ipynb":
            note = "with outputs" if has_outputs(f) else "NO OUTPUTS"
        lines.append(f"{rel}\t{f.stat().st_size}\t{sha256(f)}\t{note}")
    (out / "MANIFEST.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return warnings


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "submission")
    ap.add_argument("--executed-notebooks", type=Path, default=None)
    args = ap.parse_args(argv)
    warnings = export(args.out, args.executed_notebooks)
    print(f"wrote {args.out}")
    print((args.out / "MANIFEST.txt").read_text(encoding="utf-8"))
    for w in warnings:
        print("WARNING:", w)
    return 0


if __name__ == "__main__":
    sys.exit(main())
